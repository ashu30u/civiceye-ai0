// ============================================================================
// Intelligent Multilingual Semantic Disease Identifier
// Handles Hindi, Hinglish, English text, and Voice Transcripts
// ============================================================================
export function identifyCropDisease(queryText = "", voiceText = "", forcedKey = null) {
  if (forcedKey && CROP_DIAGNOSES[forcedKey]) {
    return CROP_DIAGNOSES[forcedKey];
  }

  const raw = `${queryText || ""} ${voiceText || ""}`.toLowerCase().trim();

  // If completely empty, default to blast demo
  if (!raw) {
    return CROP_DIAGNOSES.blast;
  }

  // 1. Check for EXCESS NITROGEN / EXCESS GREEN / JYADA HARI / UREA TOXICITY
  // e.g. "dhan ki fasl jyada hari color ho gayi hai", "gehri hari", "jyada hara", "excess green", "dark green"
  const isExcessGreen =
    raw.includes("hari") ||
    raw.includes("हरी") ||
    raw.includes("hara") ||
    raw.includes("हरा") ||
    raw.includes("green") ||
    raw.includes("dark green") ||
    raw.includes("urea") ||
    raw.includes("यूरिया") ||
    raw.includes("nitrogen") ||
    raw.includes("नाइट्रोजन") ||
    raw.includes("lodging") ||
    raw.includes("gir rahi") ||
    raw.includes("गिरने") ||
    raw.includes("lambai jyada") ||
    raw.includes("bada ho gaya");

  const isExplicitExcess =
    raw.includes("jyada") ||
    raw.includes("ज्यादा") ||
    raw.includes("अधिक") ||
    raw.includes("adhik") ||
    raw.includes("bahut") ||
    raw.includes("बहुत") ||
    raw.includes("dark") ||
    raw.includes("gehra") ||
    raw.includes("गहरा") ||
    raw.includes("excess") ||
    raw.includes("color ho gayi") ||
    raw.includes("rang ho gaya");

  if (isExcessGreen && isExplicitExcess) {
    return CROP_DIAGNOSES.excess_nitrogen;
  }

  // 2. Check for KHAIRA ROG / ZINC DEFICIENCY in Paddy
  // e.g. "khaira", "zinc", "katthai", "tamba dhabba", "peeli", "peela pan"
  const isKhaira =
    raw.includes("खैरा") ||
    raw.includes("khaira") ||
    raw.includes("जिंक") ||
    raw.includes("zinc") ||
    raw.includes("जस्ता") ||
    raw.includes("कत्थई") ||
    raw.includes("katthai") ||
    raw.includes("tamba") ||
    raw.includes("तांबे") ||
    raw.includes("jang") ||
    raw.includes("जंग");

  if (isKhaira) {
    return CROP_DIAGNOSES.khaira;
  }

  // 3. Check for STEM BORER / TANA CHHEDAK / DEAD HEART / WHITE EAR
  // e.g. "gobh sukh", "tana ched", "safed bali", "dead heart"
  const isStemBorer =
    raw.includes("गोभ") ||
    raw.includes("gobh") ||
    raw.includes("gob") ||
    raw.includes("तना छेद") ||
    raw.includes("तनाछेदक") ||
    raw.includes("tana ched") ||
    raw.includes("tana chhedak") ||
    raw.includes("stem borer") ||
    raw.includes("सफेद बाली") ||
    raw.includes("safed bali") ||
    raw.includes("safed baali") ||
    raw.includes("dead heart") ||
    raw.includes("white ear") ||
    (raw.includes("sukh rahi") && (raw.includes("dhan") || raw.includes("धान")));

  if (isStemBorer) {
    return CROP_DIAGNOSES.stem_borer;
  }

  // 4. Check for SHEATH BLIGHT / TANA JHULSA
  // e.g. "sheath blight", "sarpakar", "sanp jaise dhabbe"
  const isSheathBlight =
    raw.includes("sheath") ||
    raw.includes("शीथ") ||
    raw.includes("sarpakar") ||
    raw.includes("सर्पाकार") ||
    raw.includes("rhizoctonia") ||
    raw.includes("तने पर धब्बे") ||
    raw.includes("tane par dhabbe");

  if (isSheathBlight) {
    return CROP_DIAGNOSES.sheath_blight;
  }

  // 5. Check for BPH / BHURA MAHU / BROWN PLANTHOPPER
  // e.g. "bph", "bhura mahu", "hopper burn", "machhad"
  const isBph =
    raw.includes("bph") ||
    raw.includes("माहू") ||
    raw.includes("mahu") ||
    raw.includes("भूरा माहू") ||
    raw.includes("bhura mahu") ||
    raw.includes("hopper") ||
    raw.includes("हॉपर") ||
    raw.includes("machhad") ||
    raw.includes("मच्छर");

  if (isBph) {
    return CROP_DIAGNOSES.bph;
  }

  // 6. Check for POD BORER in Chana/Pulses
  // e.g. "chana", "fali", "illi", "sundi"
  const isPodBorer =
    raw.includes("चना") ||
    raw.includes("chana") ||
    raw.includes("फली") ||
    raw.includes("fali") ||
    raw.includes("इल्ली") ||
    raw.includes("illi") ||
    raw.includes("सुंडी") ||
    raw.includes("sundi") ||
    raw.includes("pod borer") ||
    raw.includes("छेदक") ||
    raw.includes("chedak");

  if (isPodBorer) {
    return CROP_DIAGNOSES.pod_borer;
  }

  // 7. Check for YELLOW MOSAIC in Soybean/Pulses
  // e.g. "soyabean", "mosaic", "safed makkhi", "whitefly"
  const isMosaic =
    raw.includes("मोज़ेक") ||
    raw.includes("mosaic") ||
    raw.includes("सोयाबीन") ||
    raw.includes("soyabean") ||
    raw.includes("soybean") ||
    raw.includes("सफेद मक्खी") ||
    raw.includes("safed makkhi") ||
    raw.includes("whitefly") ||
    raw.includes("उड़द") ||
    raw.includes("मूंग");

  if (isMosaic) {
    return CROP_DIAGNOSES.mosaic;
  }

  // 8. Check for LEAF CURL / PATTA MAROD in Tomato/Chilli
  // e.g. "tamatar", "mirch", "patta marod", "curl", "thrips"
  const isLeafCurl =
    raw.includes("टमाटर") ||
    raw.includes("tamatar") ||
    raw.includes("मिर्च") ||
    raw.includes("mirch") ||
    raw.includes("chilli") ||
    raw.includes("tomato") ||
    raw.includes("पत्ता मरोड़") ||
    raw.includes("patta marod") ||
    raw.includes("चुरड़ा") ||
    raw.includes("चुरडा") ||
    raw.includes("churda") ||
    raw.includes("curl") ||
    raw.includes("thrips") ||
    raw.includes("माइट");

  if (isLeafCurl) {
    return CROP_DIAGNOSES.leaf_curl;
  }

  // 9. Check for BLAST / PADDY LEAF BLAST
  // e.g. "blast", "jhulsa", "aankh jaise dhabbe", "naav jaise"
  const isBlast =
    raw.includes("झुलसा") ||
    raw.includes("jhulsa") ||
    raw.includes("blast") ||
    raw.includes("ब्लास्ट") ||
    raw.includes("आंख") ||
    raw.includes("aankh") ||
    raw.includes("नाव") ||
    raw.includes("naav") ||
    raw.includes("magnaporthe") ||
    raw.includes("pyricularia");

  if (isBlast) {
    return CROP_DIAGNOSES.blast;
  }

  // 10. Check for HEALTHY / SWASTH
  const isHealthy =
    raw.includes("स्वस्थ") ||
    raw.includes("swasth") ||
    raw.includes("healthy") ||
    raw.includes("बढ़िया") ||
    raw.includes("badhiya") ||
    raw.includes("निरोग") ||
    raw.includes("theek hai") ||
    raw.includes("achhi hai");

  if (isHealthy) {
    return CROP_DIAGNOSES.healthy;
  }

  // 11. Generic Yellowing / Peela in Paddy -> Khaira or Nitrogen
  if (raw.includes("peela") || raw.includes("पीला") || raw.includes("peeli") || raw.includes("pili")) {
    if (raw.includes("soyabean") || raw.includes("सोयाबीन")) {
      return CROP_DIAGNOSES.mosaic;
    }
    return CROP_DIAGNOSES.khaira;
  }

  // 12. If the user mentions any specific crop or symptoms not in our direct rules,
  // dynamically generate a tailored, certified ICAR diagnosis rather than falling back to blast!
  const matchedCrop =
    raw.includes("धान") || raw.includes("dhan") || raw.includes("paddy") || raw.includes("rice")
      ? "धान (Paddy / Rice)"
      : raw.includes("गेहूं") || raw.includes("gehun") || raw.includes("wheat")
      ? "गेहूं (Wheat)"
      : raw.includes("मक्का") || raw.includes("makka") || raw.includes("maize")
      ? "मक्का (Maize)"
      : raw.includes("आलू") || raw.includes("aalu") || raw.includes("potato")
      ? "आलू (Potato)"
      : raw.includes("बैंगन") || raw.includes("baigan") || raw.includes("brinjal")
      ? "बैंगन (Brinjal)"
      : raw.includes("गन्ना") || raw.includes("ganna") || raw.includes("sugarcane")
      ? "गन्ना (Sugarcane)"
      : raw.includes("सरसों") || raw.includes("sarson") || raw.includes("mustard")
      ? "सरसों (Mustard)"
      : raw.includes("कपास") || raw.includes("kapas") || raw.includes("cotton")
      ? "कपास (Cotton)"
      : "फसल (Crop)";

  const matchedIssue =
    raw.includes("कीड़ा") || raw.includes("keeda") || raw.includes("kida") || raw.includes("insect")
      ? "कीट प्रकोप (Insect Pest Infestation)"
      : raw.includes("सड़न") || raw.includes("sadan") || raw.includes("rot")
      ? "सड़न व फफूंद रोग (Fungal Rot Disorder)"
      : raw.includes("धब्बे") || raw.includes("dhabbe") || raw.includes("spot")
      ? "पत्ती धब्बा विकार (Leaf Spot Pathology)"
      : raw.includes("सूख") || raw.includes("sukh") || raw.includes("dry")
      ? "पौधों का सूखना व विल्ट (Wilt & Desiccation)"
      : "फसल स्वास्थ्य समस्या (Crop Health Pathology)";

  return generateCustomDiagnosis(raw, matchedCrop, matchedIssue);
}

